import { test, expect } from '@playwright/test';
test('register, circle, mood, profile, preferences and session journey', async ({ page, browser }, info) => {
  test.setTimeout(60000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const email = `friend-${info.project.name}@example.com`, password = 'a-very-long-private-password';
  await page.goto('/signup');
  await page.getByLabel('Display name', { exact: true }).fill('Maya');
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page).toHaveURL(/\/circles$/);
  await page.getByRole('button', { name: 'Create a circle', exact: true }).click();
  await page.getByLabel('Circle name', { exact: true }).fill('Sunday people');
  await page.getByLabel('Description', { exact: true }).fill('A little space for us.');
  await page.getByRole('button', { name: 'Create circle', exact: true }).click();
  await expect(page.getByRole('heading', { name: /Sunday people/ })).toBeVisible();
  await page.getByRole('button', { name: 'Create invitation', exact: true }).click();
  await expect(page.getByLabel('Invitation link', { exact: true })).toHaveValue(/invite=/);
  const invitationLink = await page.getByLabel('Invitation link', { exact: true }).inputValue();
  await page.getByRole('link', { name: 'Back to your feed', exact: true }).click();
  await page.getByRole('button', { name: '🌿 How are you feeling today?', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('button', { name: '🌿 calm', exact: true }).click();
  await dialog.getByLabel('A few words, if you like', { exact: true }).fill('A quiet cup of tea with my people.');
  if (info.project.name === 'desktop') {
    // Only the external search response is a fixture; the post still persists through the real API.
    await page.route('https://itunes.apple.com/search?**', route => route.fulfill({ json: { results: [{ trackId: 123, trackName: 'A test song', artistName: 'Test artist', artworkUrl100: 'https://is1-ssl.mzstatic.com/test.jpg', previewUrl: 'https://audio-ssl.itunes.apple.com/test.m4a' }] } }));
    await dialog.getByText('Add a song instead of a photo', { exact: true }).click();
    await dialog.getByRole('textbox', { name: 'Song or artist', exact: true }).fill('A test song');
    await dialog.getByRole('button', { name: 'Search music', exact: true }).click();
    await dialog.getByRole('button', { name: 'Choose', exact: true }).click();
    await expect(dialog.getByText('A test song — Test artist', { exact: true })).toBeVisible();
  }
  await dialog.getByRole('button', { name: 'Share your vibe', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByText('A quiet cup of tea with my people.', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText('A quiet cup of tea with my people.', { exact: true })).toBeVisible();
  if (info.project.name === 'desktop') await expect(page.getByText('A test song', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Edit', exact: true }).click();
  await page.getByRole('dialog').getByRole('textbox', { name: 'Your words', exact: true }).fill('A quieter cup of tea.');
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(page.getByText('A quieter cup of tea.', { exact: true })).toBeVisible();
  if (info.project.name === 'desktop') {
    const friendContext = await browser.newContext({ baseURL: 'http://localhost:4173' });
    const friend = await friendContext.newPage();
    await friend.goto('/signup');
    await friend.getByLabel('Display name', { exact: true }).fill('Noah');
    await friend.getByLabel('Email', { exact: true }).fill('noah@example.com');
    await friend.getByLabel('Password', { exact: true }).fill(password);
    await friend.getByRole('button', { name: 'Create account', exact: true }).click();
    await expect(friend).toHaveURL(/\/circles$/);
    await friend.goto(invitationLink);
    await friend.getByRole('button', { name: 'Join circle', exact: true }).click();
    await expect(friend.getByRole('heading', { name: /Sunday people/ })).toBeVisible();
    await friend.getByRole('link', { name: 'Back to your feed', exact: true }).click();
    await expect(friend.getByText('A quieter cup of tea.', { exact: true })).toBeVisible();
    await friend.getByRole('button', { name: 'Thinking of you', exact: true }).click();
    await expect(friend.getByRole('button', { name: 'Thinking of you', exact: true })).toHaveAttribute('aria-pressed', 'true');
    await page.goto('/activity');
    await expect(page.getByText(/Noah sent/)).toBeVisible();
    await page.getByRole('link', { name: 'View mood', exact: true }).click();
    await page.getByText('Kind words from your people', { exact: true }).click();
    await expect(page.getByText('🌸 Noah', { exact: true })).toBeVisible();
    await page.goto('/messages');
    await page.getByRole('button', { name: 'New message', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: /Noah/ }).click();
    await page.getByRole('textbox', { name: 'Message text', exact: true }).fill('Tea later, Noah?');
    await page.getByRole('button', { name: 'Send message', exact: true }).click();
    await expect(page.locator('[data-message-id]').getByText('Tea later, Noah?', { exact: true })).toBeVisible();
    const chatUrl = page.url();
    await page.reload();
    await expect(page.locator('[data-message-id]').getByText('Tea later, Noah?', { exact: true })).toBeVisible();
    await friend.goto('/messages');
    await friend.getByRole('button').filter({ hasText: 'Maya' }).click();
    await expect(friend.locator('[data-message-id]').getByText('Tea later, Noah?', { exact: true })).toBeVisible();
    await friend.getByRole('textbox', { name: 'Message text', exact: true }).fill('See you there!');
    await friend.getByRole('button', { name: 'Send message', exact: true }).click();
    await expect(page.locator('[data-message-id]').getByText('See you there!', { exact: true })).toBeVisible({ timeout: 10000 });
    await expect(page).toHaveURL(chatUrl);
    await page.screenshot({ path: 'test-results/messages-desktop.png', fullPage: true });
    await friendContext.close();
    await page.goto('/feed');
  } else {
    await page.goto('/messages');
    await page.getByRole('button', { name: 'Groups', exact: true }).click();
    await page.getByRole('button').filter({ hasText: 'Sunday people' }).click();
    await page.getByRole('textbox', { name: 'Message text', exact: true }).fill('A hello to our circle.');
    await page.getByRole('button', { name: 'Send message', exact: true }).click();
    await expect(page.locator('[data-message-id]').getByText('A hello to our circle.', { exact: true })).toBeVisible();
    await page.reload();
    await expect(page.locator('[data-message-id]').getByText('A hello to our circle.', { exact: true })).toBeVisible();
    await page.screenshot({ path: 'test-results/messages-mobile.png', fullPage: true });
    await page.getByRole('button', { name: 'Back to conversations', exact: true }).click();
    await expect(page.getByRole('button', { name: 'New message', exact: true })).toBeVisible();
    await page.goto('/feed');
  }
  await expect(page.getByText('A quieter cup of tea.', { exact: true })).toBeVisible();
  await page.screenshot({ path: `test-results/feed-${info.project.name}.png`, fullPage: true });
  await page.getByRole('link', { name: 'View check-in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'A little check-in', exact: true })).toBeVisible();
  await page.goto('/profile');
  await page.getByRole('button', { name: 'Edit profile', exact: true }).click();
  await page.getByRole('dialog').getByLabel('Username', { exact: true }).fill(`maya_${info.project.name}`);
  await page.getByRole('dialog').getByRole('textbox', { name: 'Bio', exact: true }).fill('Tea, slow mornings and my people.');
  await page.getByRole('button', { name: 'Save profile', exact: true }).click();
  await expect(page.getByText('Tea, slow mornings and my people.', { exact: true })).toBeVisible();
  await page.goto('/settings');
  await page.getByRole('combobox', { name: 'Timezone', exact: true }).selectOption('Asia/Manila');
  await page.getByLabel('Reaction notifications', { exact: true }).uncheck();
  await page.getByRole('button', { name: 'Save preferences', exact: true }).click();
  await expect(page.getByText('Preferences saved.', { exact: true })).toBeVisible();
  await page.goto('/memories');
  await expect(page.getByRole('heading', { name: 'Your days are still unfolding.', exact: true })).toBeVisible();
  await page.goto('/activity');
  if (info.project.name === 'desktop') {
    await page.getByRole('button', { name: 'Mark all as read', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Mark all as read', exact: true })).toBeDisabled();
  } else await expect(page.getByRole('heading', { name: 'All quiet for now.', exact: true })).toBeVisible();
  await page.goto('/settings');
  await page.getByRole('button', { name: 'Log out', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await page.getByPlaceholder('Email', { exact: true }).fill(email);
  await page.locator('input[type=password]').fill(password);
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await expect(page).toHaveURL(/\/feed$/);
  await expect(page.getByText('A quieter cup of tea.', { exact: true })).toBeVisible();
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', await page.locator('body').evaluate(el => el.clientWidth));
  let sessionUnavailable = true;
  await page.route('**/api/auth/get-session', route => sessionUnavailable
    ? route.fulfill({ status: 503, json: { message: 'Temporary test outage' } })
    : route.continue());
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Miwi is taking a moment', exact: true })).toBeVisible();
  sessionUnavailable = false;
  await expect(page.getByText('A quieter cup of tea.', { exact: true })).toBeVisible({ timeout: 15000 });
  expect(errors).toEqual([]);
});
